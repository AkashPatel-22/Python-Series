# Indexing in String
# -- index in sequence represents the position value of individual elements
# i.e. characters in case of string . so indexing lets us access individual
# characters in string.


#  python follows Zero-Based indexing i.e. first character is at index -'0'.

# example

s = "Python"

print(s[0]) # 'P' 
print(s[3]) # 'h' 
print(s[-1]) # 'n' --> (negative index: last character) 