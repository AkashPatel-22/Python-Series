# List Methods.

# len() - length of the string.
# append(elements)- adds an elements to the end.
# insert(idx, elements) - add at specific position.
# sort() - sorts in ascending/alphabetical order.
# reverse() - flips the order of elements.

nums = [5, 9, 2]
# print(len( nums)) #3

nums.append(10)
print(nums)

nums.insert(1,55)
print(nums)

nums.sort()
print(nums)

nums.reverse()
print(nums)